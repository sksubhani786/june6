package June6;

public class Data_Types {

	public static void main(String[] args) 
	{
		byte by = 100;   //-128 to 127
		short sh =500;  //-32768 to 32767
		int i= 3200;    //-214483648 to 214483648
		long l= 97845126l;
		float fl = 23.05f;
		double db = 1542.78459;
		char ch = 'A';
		boolean bl=false;
		
		System.out.println("Byte value is:"+by);
		System.out.println("short value is:"+sh);
		System.out.println("int value is:"+i);
		System.out.println("long value is:"+l);
		System.out.println("float value is:"+fl);
		System.out.println("double value is:"+db);
		System.out.println("char value is:"+ch);
		System.out.println("boolean value is:"+bl);
		
		
		
	}

}
